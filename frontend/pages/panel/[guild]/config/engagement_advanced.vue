        Configuration des rappels en messages privés, déclencheurs automatiques de mots et commandes personnalisées.
      </p>

      <div class="config-item">
        <div class="config-label-group">
          <label class="config-label">Activer les Rappels Automatiques</label>
          <span class="config-hint">Permet aux membres de programmer des rappels /remind.</span>
        </div>
        <label class="switch">
          <input v-model="config.reminders_enabled" type="checkbox" />
          <span class="slider"></span>
        </label>
      </div>

      <div class="config-item">
        <div class="config-label-group">
          <label class="config-label">Activer les Mots-Clés Déclencheurs (Triggers)</label>
          <span class="config-hint">Répond automatiquement quand un mot ou une phrase configurée est détectée.</span>
        </div>
        <label class="switch">
          <input v-model="config.word_triggers_enabled" type="checkbox" />
          <span class="slider"></span>
        </label>
      </div>

      <div class="config-item">
        <div class="config-label-group">
          <label class="config-label">Activer les Commandes Personnalisées</label>
          <span class="config-hint">Permet de créer des commandes dynamiques avec préfixe !.</span>
        </div>
        <label class="switch">
          <input v-model="config.custom_commands_enabled" type="checkbox" />
          <span class="slider"></span>
        </label>
      </div>

      <div class="config-actions-bar">
        <button class="btn-primary" :disabled="isSaving" @click="saveConfig">
          {{ isSaving ? 'Enregistrement...' : '💾 Sauvegarder Engagement Avancé' }}
        </button>
      </div>
    </div>
  </div>
</template>

<script setup lang="ts">
import { onMounted } from 'vue';
import { useRoute } from 'vue-router';
import { useConfigFeature } from '~/composables/useConfigFeature.ts';

definePageMeta({
  title: 'Configuration Engagement Avancé',
  hidden: true
});

useSeoMeta({
  title: 'Engagement Avancé - Configuration',
  description: 'Configuration des rappels, triggers et commandes personnalisées'
});

const route = useRoute();
const guildId = (route.params.guild as string) || 'default';

const { config, isLoading, isSaving, load, save } = useConfigFeature('engagement_advanced', {
  defaultConfig: {
    reminders_enabled: true,
    word_triggers_enabled: true,
    custom_commands_enabled: true
  }
});

async function saveConfig() {
  await save(config.value, guildId);
}

onMounted(() => {
  load(guildId);
});
</script>

